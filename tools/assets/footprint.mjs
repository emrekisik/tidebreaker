// Measures the outline of each island model (GAME_DESIGN.md §12.5) and writes
// apps/client/src/render/islandFootprints.ts. The client bends a model so its coast follows the
// island's collision outline, which needs to know how far the model's own coast is from its center
// in every direction. Run it again (pnpm assets:footprint) when an island model changes.
//   - measured on the model's largest connected piece (loose rocks and huts are ignored)
//   - in the frame the client uses: footprint scaled to 1 unit, centered, sea surface at y = 0
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const FILES = ['island_rocky', 'island_tropical'];
const BINS = 64;
/** Only the low part of the model counts as coast (mountains rise out of it). */
const COAST_HEIGHT = 0.3;
const SHRINK = 1.04;

const io = new NodeIO().registerExtensions(ALL_EXTENSIONS);
const out = {};
for (const name of FILES) {
  const doc = await io.read(join(root, 'models', `${name}.glb`));
  const prim = doc.getRoot().listMeshes()[0].listPrimitives()[0];
  const pos = prim.getAttribute('POSITION');
  const idx = prim.getIndices().getArray();
  const n = pos.getCount();
  const p = [0, 0, 0];

  // Whole-mesh box: the same fit the client applies (longer side = 1, centered).
  const lo = [Infinity, Infinity, Infinity];
  const hi = [-Infinity, -Infinity, -Infinity];
  for (let i = 0; i < n; i++) {
    pos.getElement(i, p);
    for (let d = 0; d < 3; d++) {
      lo[d] = Math.min(lo[d], p[d]);
      hi[d] = Math.max(hi[d], p[d]);
    }
  }
  const k = 1 / Math.max(hi[0] - lo[0], hi[2] - lo[2]);
  const mid = [(lo[0] + hi[0]) / 2, (lo[2] + hi[2]) / 2];
  const height = hi[1] - lo[1];

  // Connected pieces (vertices welded by position).
  const keyOf = new Map();
  const rep = new Int32Array(n);
  for (let i = 0; i < n; i++) {
    pos.getElement(i, p);
    const key = `${Math.round(p[0] * 1e4)},${Math.round(p[1] * 1e4)},${Math.round(p[2] * 1e4)}`;
    if (!keyOf.has(key)) keyOf.set(key, i);
    rep[i] = keyOf.get(key);
  }
  const parent = Int32Array.from({ length: n }, (_, i) => i);
  const find = (a) => {
    while (parent[a] !== a) {
      parent[a] = parent[parent[a]];
      a = parent[a];
    }
    return a;
  };
  for (let t = 0; t < idx.length; t += 3) {
    parent[find(rep[idx[t]])] = find(rep[idx[t + 1]]);
    parent[find(rep[idx[t + 1]])] = find(rep[idx[t + 2]]);
  }
  const size = new Map();
  for (let t = 0; t < idx.length; t += 3) {
    const r = find(rep[idx[t]]);
    size.set(r, (size.get(r) ?? 0) + 1);
  }
  const main = [...size.entries()].sort((a, b) => b[1] - a[1])[0][0];
  const inMain = new Uint8Array(n);
  for (let t = 0; t < idx.length; t += 3) {
    if (find(rep[idx[t]]) === main) for (let c = 0; c < 3; c++) inMain[idx[t + c]] = 1;
  }

  // Center: the middle of the main piece's footprint.
  const mlo = [Infinity, Infinity];
  const mhi = [-Infinity, -Infinity];
  for (let i = 0; i < n; i++) {
    if (!inMain[i]) continue;
    pos.getElement(i, p);
    mlo[0] = Math.min(mlo[0], p[0]);
    mhi[0] = Math.max(mhi[0], p[0]);
    mlo[1] = Math.min(mlo[1], p[2]);
    mhi[1] = Math.max(mhi[1], p[2]);
  }
  const cx = ((mlo[0] + mhi[0]) / 2 - mid[0]) * k;
  const cz = ((mlo[1] + mhi[1]) / 2 - mid[1]) * k;

  const edge = new Float64Array(BINS);
  for (let i = 0; i < n; i++) {
    if (!inMain[i]) continue;
    pos.getElement(i, p);
    if ((p[1] - lo[1]) / height > COAST_HEIGHT) continue;
    const dx = (p[0] - mid[0]) * k - cx;
    const dz = (p[2] - mid[1]) * k - cz;
    const th = (((Math.atan2(dz, dx) / (Math.PI * 2)) % 1) + 1) % 1;
    const b = Math.min(BINS - 1, Math.round(th * BINS) % BINS);
    edge[b] = Math.max(edge[b], Math.hypot(dx, dz));
  }
  // Fill empty bins from their neighbors, then smooth around the circle.
  for (let pass = 0; pass < BINS; pass++) {
    for (let b = 0; b < BINS; b++) {
      if (edge[b] > 0) continue;
      const a = edge[(b + BINS - 1) % BINS];
      const c = edge[(b + 1) % BINS];
      if (a > 0 && c > 0) edge[b] = (a + c) / 2;
      else if (a > 0 || c > 0) edge[b] = a > 0 ? a : c;
    }
  }
  const smooth = Float64Array.from(edge, (_, b) => {
    let s = 0;
    for (let d = -2; d <= 2; d++) s += edge[(b + d + BINS) % BINS] * (3 - Math.abs(d));
    return (s / 9) * SHRINK;
  });
  out[name] = { cx, cz, edge: [...smooth].map((v) => Math.round(v * 1000) / 1000) };
  console.log(
    name,
    'center',
    cx.toFixed(3),
    cz.toFixed(3),
    'edge',
    Math.min(...smooth).toFixed(2),
    '..',
    Math.max(...smooth).toFixed(2),
  );
}

const text = `// Generated by tools/assets/footprint.mjs (pnpm assets:footprint). Do not edit by hand.
// Coast outline of each island model in its fitted frame (see render/assets.ts, fitProp):
// \`edge[i]\` is the distance from (cx, cz) to the coast toward angle i / 64 * 2 PI (atan2(z, x)).

export interface Footprint {
  cx: number;
  cz: number;
  edge: readonly number[];
}

export const ISLAND_FOOTPRINTS: Readonly<Record<string, Footprint>> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(join(root, 'apps/client/src/render/islandFootprints.ts'), text);
